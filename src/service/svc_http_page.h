/**
 * @file    svc_http_page.h
 * @brief   回放服务的**静态页面**(浏览器直接当客户端用)
 *
 * @details
 * ─────────────────────────────────────────────────────────────────
 *  为什么把 HTML 放在板子上而不是让 PC 端另写一个客户端
 * ─────────────────────────────────────────────────────────────────
 *  真实监控产品的客户端**就是浏览器**(海康/Axis 都如此):设备自己把页面发出去,
 *  用户不用装任何东西。我们已经有 HTTP 服务了, 顺手多发一个静态页几乎零成本,
 *  却立刻得到"能看录像、能拖进度条、能锁定"的可用客户端。
 *
 *  页面里做的事(全部走我们已有的接口, 没有第二个协议):
 *      · `GET /recordings`          取分段列表(含 `uri` / `lock_uri`)→ 列表 + 时间轴
 *      · `<video src=uri>`          播放;浏览器拖进度条会**自动发 `Range` 请求**
 *      · `PUT lock_uri` (body 1/0)  锁定 / 解锁
 *      · `GET /playlist.m3u`        交给 VLC/mpv 连续回放的播放列表
 *
 *  直播(RTSP)浏览器播不了 —— 页面里只把 `rtsp://…` 地址显示出来, 让人用 VLC 打开。
 *  这是**如实**的做法: 不假装浏览器能播 RTSP。
 *
 * @note 页面是**常量字符串**, 不给它单独的构建步骤(不引入前端工具链)。
 * @note 只读、无状态;任何线程都可以发它。
 */
