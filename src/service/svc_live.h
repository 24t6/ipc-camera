/**
 * @file    svc_live.h
 * @brief   MJPEG 实时预览服务(浏览器里看**实时画面**)
 *
 * @details
 * ─────────────────────────────────────────────────────────────────
 *  【模块职责】一个独立的 HTTP 服务线程:把"按需开启的 MJPEG 编码通道"里的 JPEG 帧
 *             用 `multipart/x-mixed-replace` 推给浏览器 ⇒ **零安装、零插件**的实时画面
 *  【依赖方向】依赖 infra_netio / infra_log / proto_http / **bsp_mpp**(要那路 MJPEG)
 *  【线程模型】自己起 1 个线程(线程名 `ipc_live`);**单线程 + poll 多路复用**,
 *             一帧只取一次、广播给所有客户端;客户端**有界**(`SVC_LIVE_MAX_CLIENTS`)
 *  【资源边界】无动态分配;文件级静态:一帧缓冲 ~192KB + 客户端槽(见 .c)
 *
 * ─────────────────────────────────────────────────────────────────
 *  为什么是**独立端口**(而不是并进 8080 那个回放服务)
 * ─────────────────────────────────────────────────────────────────
 *  回放服务是**串行**的(一次服务一个请求, ADR-5):列表/取流/页面能在几十毫秒内答完,
 *  所以串行没问题。而 MJPEG 是**一条长期不关的连接** —— 并进去就等于"谁在看实时画面,
 *  谁就把回放服务占住了"。所以:
 *      · 回放服务(8080)保持它被验证过的串行模型, **一行线程模型都不用改**
 *      · 实时画面另起一个端口(默认 8081)与线程, 互相不牵连
 *  页面上用 `<img src="http://<板子IP>:8081/live.mjpg">` 就能显示(浏览器天然支持
 *  `multipart/x-mixed-replace`, 不需要 JS 解码)。
 *
 * ─────────────────────────────────────────────────────────────────
 *  ⭐ 为什么"通道必须按需启停"(A22 的实测结论)
 * ─────────────────────────────────────────────────────────────────
 *  B027 的老教训是"没有人取流的编码通道会把整条流水线拖死"(主路停在 205 帧)。
 *  2026-09-20 的孤立实验(`tools/jpeg_smoke.c`, 见 `STATUS.md` A22)测到:
 *      · 第一个客户端来 → 建 MJPEG 通道(**640x360@10fps**, 每帧 ~16KB)
 *      · 主路(H.264 30fps)在 MJPEG 活动、空闲、甚至"开收流但不取 6 秒"时
 *        **都没有掉帧**(30.0~30.2 fps)
 *      · 拆掉通道后主路照旧 30 fps
 *  也就是说 MJPEG 的"饿死"看起来**不像** H.264 那样反压 VPSS(它更像"缓冲满就丢帧")。
 *  **但本模块仍然不依赖这个结论**:最后一个客户端一走就**整条拆掉**通道, 让 MPP 回到
 *  "只有主路"这个被反复验证过的状态 —— 理由: ①省电与内存带宽 ②避免缓冲满后的
 *  不确定状态 ③B045 的教训(别把没验过的行为当依据)。
 *
 * ─────────────────────────────────────────────────────────────────
 *  对外接口
 * ─────────────────────────────────────────────────────────────────
 *      GET /live.mjpg        MJPEG 流(`/live`、`/stream` 等价)
 *      GET /live.mjpg?t=...  带时间戳的写法(页面用它绕开浏览器缓存)
 *      GET /help             纯文本说明
 *  ⚠️ 与回放服务一样**没有鉴权** —— 局域网演示定位, 不要暴露到公网。
 */
#ifndef __SVC_LIVE_H__
#define __SVC_LIVE_H__

#include <stdint.h>

/** 默认端口(与 RTSP 8554、回放 8080 都分开) */
#define SVC_LIVE_DEFAULT_PORT 8081

/** 最多同时几个客户端(多了会拒绝;每个客户端占一个 fd 与一小段写超时预算) */
#define SVC_LIVE_MAX_CLIENTS  4

/** 实时画面的配置 */
typedef struct {
    const char *bind_ip;    /**< 绑定地址, 如 "0.0.0.0" */
    uint16_t    port;       /**< 端口; 0 = 用 `SVC_LIVE_DEFAULT_PORT` */
    int         qfactor;    /**< JPEG 质量 1~99(0 = 用默认 80) */
    int         fps;        /**< 目标帧率(0 = 用默认 10) */
} svc_live_cfg_t;

/** 实时服务统计(日志与验收用) */
typedef struct {
    uint64_t conns;         /**< 接受过的连接数 */
    uint64_t frames;        /**< 广播出去的 JPEG 帧数 */
    uint64_t bytes;         /**< 广播出去的字节数(含分片头) */
    uint64_t dropped;       /**< 因为跟不上/写失败被丢掉的客户端数 */
    uint64_t frame_errors;  /**< 取 JPEG 帧失败次数 */
    int      clients;       /**< 当前客户端数 */
} svc_live_stats_t;

/**
 * @brief 启动实时服务(建监听 socket + 起线程)。
 *
 * @param[in] cfg 配置(拷进内部;NULL = 全默认)
 * @return 0 成功; 负值失败(端口被占 / 线程建不起来)
 *
 * @note ⚠️ MPP 通道**不在这里开** —— 等第一个客户端连上才开(按需启停, 见文件头)。
 *       所以这个函数可以在 `bsp_mpp_init()` 之前调用。
 * @note 重复调用(已启动)返回 0。
 */
int svc_live_start(const svc_live_cfg_t *cfg);

/** @brief 停服务:通知线程退出 → 打断在途 I/O → join → 关监听;并**确保 MJPEG 通道关掉**。 */
void svc_live_stop(void);

/** @brief 服务是否在运行。@return 1 = 在运行 */
int svc_live_is_running(void);

/** @brief 实际监听端口(配 0 时由内核选, 这里给真实值)。 */
uint16_t svc_live_port(void);

/** @brief 取统计快照。 */
void svc_live_get_stats(svc_live_stats_t *out);

#endif /* __SVC_LIVE_H__ */
